"""build_section_dataset.py  (Python 3) -- H289 Phase-2: cross-section derived dataset

Reads every per-section meter index (meter_verdicts_<section>.jsonl, all gitignored
+ regenerable) and emits SECTIONS_DATASET.md: the cross-section verdict distribution
(clean / review / suspect / non-clean%) and the top base-meter census per section.
This is the "does the meter-QA technology generalize across GRETIL genres, and what
does each genre's metrical profile look like" dataset of handoff H289 Phase 2.

  python build_section_dataset.py [out=SECTIONS_DATASET.md]
"""
import os
import sys
import json
import collections

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import variety_stats as vs   # noqa: E402  (reuse _base_meter)

sys.stdout.reconfigure(encoding='utf-8')
sys.stderr.reconfigure(encoding='utf-8')
HERE = os.path.dirname(os.path.abspath(__file__))

# section key -> (label, genre, index file, corpus note). Order = presentation order.
SECTIONS = [
    ('kavya',     'Kāvya (baseline)',        'meter_verdicts.jsonl',
     '56 texts — the H251/H277 base section'),
    ('pilot',     'Subhāṣita + Stotra',      'meter_verdicts_pilot.jsonl',
     'Bhartṛhari Śatakatraya, 108 Buddhist Stotras, Abhinavagupta Kramastotra (H289 Phase 1)'),
    ('purana',    'Purāṇa (narrative)',      'meter_verdicts_purana.jsonl',
     'Mārkaṇḍeya-purāṇa 1–93, first 1500-block sample'),
    ('epic',      'Epic',                    'meter_verdicts_epic.jsonl',
     'Vālmīki Rāmāyaṇa (southern rec. 2), first 1500-block sample'),
    ('subhasita', 'Subhāṣita anthology',     'meter_verdicts_subhasita.jsonl',
     'Vidyākara Subhāṣitaratnakoṣa, first 1500-block sample'),
    ('smrti',     'Verse-śāstra (Dharma)',   'meter_verdicts_smrti.jsonl',
     'Manusmṛti, first 1500-block sample'),
]


def read_index(path):
    counts = collections.Counter()
    meters = collections.Counter()
    n = 0
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            counts[rec['verdict']] += 1
            n += 1
            label = (rec.get('skrutable') or {}).get('meter') or ''
            meters[vs._base_meter(label) if label else '(none identified)'] += 1
    return n, counts, meters


def main(out_path):
    rows = []
    per_section_meters = []
    for key, label, fname, note in SECTIONS:
        path = os.path.join(HERE, fname)
        if not os.path.exists(path):
            sys.stderr.write("build_section_dataset: SKIP %s (%s not built)\n" % (key, fname))
            continue
        n, counts, meters = read_index(path)
        clean = counts.get('clean', 0)
        review = counts.get('review', 0)
        suspect = counts.get('suspect', 0)
        nonclean = review + suspect
        rows.append((label, note, n, clean, review, suspect,
                     100.0 * nonclean / n if n else 0.0))
        top = [(m, c) for m, c in meters.most_common(6) if m != '(none identified)'][:5]
        per_section_meters.append((label, n, top))

    lines = []
    lines.append("# Cross-section derived dataset — GRETIL meter QA beyond Kāvya")
    lines.append("")
    lines.append("_Auto-generated by [`build_section_dataset.py`](build_section_dataset.py) from the "
                 "(gitignored, regenerable) per-section meter indices. Regenerate after a rebuild._")
    lines.append("")
    lines.append("Handoff [H289](https://github.com/gasyoun/Uprava/blob/main/handoffs/"
                 "H289-Opus_SanskritSpellCheck_gretil_other_sections_pilot_07.07.26.md) Phase 2. "
                 "Each non-Kāvya section is a **first-1500-block sample** (H289 guard: sample large "
                 "sections, never fetch-and-build whole). Verdict = the three-way skrutable+chanda+"
                 "vidyut vote; non-clean% is the review+suspect share, the meter-corroboration signal.")
    lines.append("")
    lines.append("## Verdict distribution by section")
    lines.append("")
    lines.append("| Section | Corpus | Verses | Clean | Review | Suspect | Non-clean % |")
    lines.append("|---|---|---:|---:|---:|---:|---:|")
    tot_n = tot_clean = tot_review = tot_suspect = 0
    for label, note, n, clean, review, suspect, pct in rows:
        lines.append("| %s | %s | %d | %d | %d | %d | **%.1f%%** |"
                     % (label, note, n, clean, review, suspect, pct))
        tot_n += n
        tot_clean += clean
        tot_review += review
        tot_suspect += suspect
    if tot_n:
        lines.append("| **All sections** | — | **%d** | %d | %d | %d | **%.1f%%** |"
                     % (tot_n, tot_clean, tot_review, tot_suspect,
                        100.0 * (tot_review + tot_suspect) / tot_n))
    lines.append("")
    lines.append("## Top base meters per section")
    lines.append("")
    for label, n, top in per_section_meters:
        pretty = ', '.join("%s (%.0f%%)" % (m, 100.0 * c / n if n else 0) for m, c in top)
        lines.append("- **%s** — %s" % (label, pretty or '(none identified)'))
    lines.append("")

    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    sys.stderr.write("build_section_dataset: %d sections, %d verses total -> %s\n"
                     % (len(rows), tot_n, out_path))


if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'SECTIONS_DATASET.md')
    main(out)
